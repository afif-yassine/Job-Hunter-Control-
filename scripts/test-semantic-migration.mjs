import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '../tools/semantic-db-test/node_modules/@electric-sql/pglite/dist/index.js';
import { vector } from '../tools/semantic-db-test/node_modules/@electric-sql/pglite-pgvector/dist/index.js';

const pg = new PGlite({ extensions: { vector } });
const u1 = '00000000-0000-0000-0000-000000000001', u2 = '00000000-0000-0000-0000-000000000002';
const o1 = '00000000-0000-0000-0000-000000000003', j1 = '00000000-0000-0000-0000-000000000004';
const vec = JSON.stringify(Array(1024).fill(0.1));
const one = async (sql, args = []) => (await pg.query(sql, args)).rows[0];
let checks = 0;
const check = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
try {
  await pg.exec(`create schema auth; create schema extensions; create extension vector with schema extensions;
    create role anon; create role authenticated; create role service_role bypassrls;
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub', true),'')::uuid$$;
    grant usage on schema auth,extensions to anon,authenticated,service_role;
    create table auth.users(id uuid primary key);
    create table public.offers(id uuid primary key,title text,description text,location text,contract_type text,categories text[],status text,summary jsonb,embedding extensions.vector(768));
    create table public.candidate_profiles(user_id uuid primary key,profile jsonb,skills text[],embedding extensions.vector(768),embedding_hash text);
    create table public.jobs(id uuid primary key,user_id uuid,offer_id uuid);
    alter table offers enable row level security; alter table candidate_profiles enable row level security; alter table jobs enable row level security;
    create policy offers_read on offers for select to authenticated using(true);
    create policy profile_owner on candidate_profiles for all to authenticated using(user_id=(select auth.uid())) with check(user_id=(select auth.uid()));
    create policy jobs_owner on jobs for all to authenticated using(user_id=(select auth.uid())) with check(user_id=(select auth.uid()));
    grant select on offers to authenticated; grant select,update on candidate_profiles to authenticated; grant select on jobs to authenticated;
    grant all on offers,candidate_profiles,jobs to service_role;`);
  await pg.exec(await readFile('supabase/migrations/20261006145105_versioned_perplexity_vectors.sql', 'utf8'));
  await pg.query('insert into auth.users values($1),($2)', [u1,u2]);
  await pg.query(`insert into offers(id,title,description,status,summary) values($1,'Python','API','open','{"skills":["python","sql"]}')`, [o1]);
  await pg.query(`insert into candidate_profiles(user_id,profile,skills) values($1,'{"skills":{"tools":["Python"]}}','{python}'),($2,'{}','{}')`, [u1,u2]);
  await pg.query('insert into jobs values($1,$2,$3)', [j1,u1,o1]);
  const source = { title:'Python',description:'API',location:null,contract_type:null,categories:null };
  await pg.exec('set role service_role');
  const claimed=(await one('select claim_semantic_offers(50) rows')).rows;
  check(claimed.length,1);
  check((await one('select claim_semantic_offers(50) rows')).rows.length,0);
  check((await one('select set_semantic_offer_embeddings($1::jsonb) n', [JSON.stringify([{id:o1,token:claimed[0].semantic_claim_token,source,hash:'v1',embedding:vec}])])).n, 1);
  check((await one('select set_semantic_offer_embeddings($1::jsonb) n', [JSON.stringify([{id:o1,source,hash:'v1',embedding:vec}])])).n, 0);
  await pg.exec('reset role');
  await pg.query(`select set_config('request.jwt.claim.sub',$1,false)`,[u1]); await pg.exec('set role authenticated');
  const profileToken=(await one('select claim_semantic_profile($1,$2) token',[u1,'p1'])).token;
  assert.ok(profileToken); checks++;
  check((await one('select claim_semantic_profile($1,$2) token',[u1,'p1'])).token,null);
  check((await one('select claim_semantic_profile($1,$2) token',[u2,'p2'])).token,null);
  check((await one(`select set_semantic_profile_embedding($1,'{"skills":{"tools":["Python"]}}','p1',$2,'{python}',$3) ok`,[u1,vec,profileToken])).ok,true);
  check((await one(`select set_semantic_profile_embedding($1,'{}','p2',$2,'{}',$3) ok`,[u2,vec,profileToken])).ok,false);
  check((await one('select count(*)::int n from candidate_profiles')).n,1);
  check((await one('select count(*)::int n from match_offers_for_me_v2(20)')).n,1);
  check((await one('select matched,missing from my_job_fit_v2()')), {matched:['python'],missing:['sql']});
  const token=(await one('select claim_document_generation($1,$2) token',[j1,u1])).token;
  assert.ok(token); checks++;
  check((await one('select claim_document_generation($1,$2) token',[j1,u1])).token,null);
  check((await one('select claim_document_generation($1,$2) token',[j1,u2])).token,null);
  await pg.query('select release_document_generation($1,$2,$3)',[j1,u1,u2]);
  check((await one('select claim_document_generation($1,$2) token',[j1,u1])).token,null);
  await pg.query('select release_document_generation($1,$2,$3)',[j1,u1,token]);
  assert.ok((await one('select claim_document_generation($1,$2) token',[j1,u1])).token); checks++;
  await pg.exec('reset role');
  await pg.query(`update offers set semantic_model='wrong-space' where id=$1`,[o1]);
  await pg.exec('set role authenticated');
  check((await one('select count(*)::int n from match_offers_for_me_v2(20)')).n,0);
  check((await one('select similarity from my_job_fit_v2()')).similarity,null);
  await pg.query(`update candidate_profiles set profile='{"skills":{"tools":["SQL"]}}' where user_id=$1`,[u1]);
  check((await one('select semantic_embedding from candidate_profiles')).semantic_embedding,null);
  await pg.exec('reset role');
  await pg.query(`update offers set description='CHANGED' where id=$1`,[o1]);
  check((await one('select semantic_embedding from offers')).semantic_embedding,null);
  await pg.exec('set role service_role');
  check((await one('select set_semantic_offer_embeddings($1::jsonb) n',[JSON.stringify([{id:o1,source,hash:'stale',embedding:vec}])])).n,0);
  await pg.exec('reset role; set role anon');
  await assert.rejects(pg.query('select * from document_generation_leases'),/permission denied/); checks++;
  await assert.rejects(pg.query('select * from match_offers_for_me_v2(20)'),/permission denied/); checks++;
  console.log(`${checks} PostgreSQL/pgvector assertions passed: migration, RLS, stale vectors, spaces and leases.`);
} finally { await pg.close(); }
